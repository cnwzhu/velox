//! 内置紧凑 `8x16` ASCII 点阵回退采样器。


pub fn sample_8x16_bilinear(rows: [u8; 16], gx_fp: i32, gy_fp: i32) -> u8 {
    let x0 = (gx_fp >> 4).clamp(0, 7);
    let y0 = (gy_fp >> 4).clamp(0, 15);
    let x1 = (x0 + 1).clamp(0, 7);
    let y1 = (y0 + 1).clamp(0, 15);
    let fx = gx_fp & 0xF;
    let fy = gy_fp & 0xF;

    let bit = |x: i32, y: i32| -> i32 {
        if ((rows[y as usize] >> (7 - x)) & 1) != 0 {
            255
        } else {
            0
        }
    };

    let c00 = bit(x0, y0);
    let c10 = bit(x1, y0);
    let c01 = bit(x0, y1);
    let c11 = bit(x1, y1);

    let top = c00 * (16 - fx) + c10 * fx;
    let bot = c01 * (16 - fx) + c11 * fx;
    let val = (top * (16 - fy) + bot * fy) >> 8;
    if val > 72 {
        ((val - 48) * 255 / 207).clamp(0, 255) as u8
    } else {
        0
    }
}

