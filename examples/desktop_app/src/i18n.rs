/// Gallery 静态多语言翻译目录（支持 `en-US`、`zh-CN`、`ja-JP` 实时热切换）。
pub static DESKTOP_CATALOG: StaticCatalog = StaticCatalog::new(
    Locale::EN_US,
    &[
        StaticLocaleTable::new(Locale::EN_US, EN_ENTRIES),
        StaticLocaleTable::new(Locale::ZH_CN, ZH_CN_ENTRIES),
        StaticLocaleTable::new(Locale::JA_JP, JA_JP_ENTRIES),
    ],
);

/// 在支持的展示语言之间顺序切换：`en-US -> zh-CN -> ja-JP -> en-US`。
#[inline]
pub fn next_demo_locale(cur: Locale) -> Locale {
    if cur.same_language(Locale::EN_US) {
        Locale::ZH_CN
    } else if cur.same_language(Locale::ZH_CN) {
        Locale::JA_JP
    } else {
        Locale::EN_US
    }
}
